    public const int FontWidth = 8;
    public const int FontHeight = 8;

    public BlockFont()
    {
        fontData = new Dictionary<char, byte[]>();
        InitializeDatabase();
    }

    public bool[,] GetCharacterGrid(char character)
    {
        bool[,] grid = new bool[FontHeight, FontWidth];

        if (!fontData.TryGetValue(character, out byte[] rows))
        {
            return grid;
        }

        for (int r = 0; r < FontHeight; r++)
        {
            byte rowByte = rows[r];
            for (int c = 0; c < FontWidth; c++)
            {
                grid[r, c] = ((rowByte >> (7 - c)) & 1) == 1;
            }
        }

        return grid;
    }

